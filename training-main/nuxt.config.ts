import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import tailwindcss from '@tailwindcss/vite'
import { news } from './app/data/news'

const siteUrl = process.env.NUXT_PUBLIC_SITE_URL ?? 'https://www.trainingcorporation.com.co'

const permanent = (to: string) => ({ redirect: { to, statusCode: 301 as const } })

// Old WordPress URLs that moved in the redesign.
const legacyRedirects = {
  '/contact': permanent('/contacto'),
  '/pqr': permanent('/contacto'),
  // Old job-posting page ("Convocatoria de empleo").
  '/director-regional': permanent('/contacto'),
  '/servicios': permanent('/portafolio-de-servicios'),
  // Old portfolio pages by business unit, now the service explorer.
  '/portafolio-de-servicios/auditoria-y-evaluacion': permanent('/servicios/auditoria'),
  '/portafolio-de-servicios/gestion-organizacional': permanent('/servicios/consultoria'),
  '/gestion-de-activos': permanent('/portafolio-de-servicios/gestion-de-activos'),
  // WordPress category archives.
  '/category/actualidad': permanent('/actualidad'),
  '/category/sin-categoria': permanent('/actualidad'),
  ...Object.fromEntries(news.map((n) => [`/${n.legacySlug}`, permanent(`/actualidad/${n.slug}`)])),
}

/**
 * Real 301s for the current host (LiteSpeed/Apache read .htaccess). The static
 * build alone can only answer old URLs with a meta refresh; search engines pass
 * ranking reliably through a 301. Canonical URLs have no trailing slash, so the
 * slash is dropped with a 301 and each path is served from its prerendered file.
 */
function htaccess() {
  const host = new URL(siteUrl).host
  const esc = (path: string) => path.slice(1).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const legacy = Object.entries(legacyRedirects)
    .map(([from, rule]) => `RewriteRule ^${esc(from)}/?$ ${rule.redirect.to} [R=301,L]`)
  return [
    '# Generated by nuxt.config.ts at build time; edit legacyRedirects there.',
    'Options -MultiViews',
    'DirectorySlash Off',
    'ErrorDocument 404 /404.html',
    'RewriteEngine On',
    '',
    '# One address: HTTPS and www.',
    'RewriteCond %{HTTPS} off [OR]',
    `RewriteCond %{HTTP_HOST} !^${host.replace(/\./g, '\\.')}$ [NC]`,
    `RewriteRule ^ https://${host}%{REQUEST_URI} [R=301,L]`,
    '',
    '# Old WordPress URLs.',
    ...legacy,
    '',
    '# No trailing slash (except the home page).',
    'RewriteCond %{REQUEST_FILENAME} !-f',
    'RewriteRule ^(.+)/$ /$1 [R=301,L]',
    '',
    '# Serve the prerendered page for a clean URL.',
    'RewriteCond %{DOCUMENT_ROOT}/$1/index.html -f',
    'RewriteRule ^(.+)$ /$1/index.html [L]',
    '',
  ].join('\n')
}

